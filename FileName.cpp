void gameView() {
    init();
    count = 1;//每次进入关卡数变为1
    maze();
    char input;//用于输入
    system("cls");
    while (gameOver != 1) {
        int ismove = 0;//用于移动判断
        gameView_Showmaze();

        input = _getch();//读入键盘输入
        if (input == 27) {
            int isstop = stopview();//调用暂停界面
            if (isstop == 1) {//继续游戏
                system("cls");
                gameView_Showmaze();
                PlayBGM();
            }
            else if (isstop == 2) {//重新开始
                maze();
                system("cls");
                gameView_Showmaze();
                PlayBGM();
            }
            else if (isstop == 3) {
                system("cls");
                menuView();//返回菜单
            }
        }
        //若输入为wasd
        if (input == 119 || input == 97 || \
            input == 115 || input == 100) 
        {
            int p = playerMove(input);
            if (p == -1)
                falseView();
            else if (p == 1)//若移动成功
                ismove = 1;//移动判断变量=1
        }
        if (ismove == 1) {//玩家移动判断
            histmove();//记录玩家移动
            getgen();//检测获取原石
            if (isWin()) {//胜利判断
                if (final() == 1) {//是否达到最后一关判断
                    winView();//胜利界面
                    system("cls");
                    menuView();
                }
                else {
                    count++;//增加关卡数
                    connect();//播放过渡动画
                }
            }
            if (isFalse())//失败判断
                falseView();//失败界面
            jiaoguanmove();//教官移动
            if (isFalse())//失败判断
                falseView();//失败界面

        }
    }
}