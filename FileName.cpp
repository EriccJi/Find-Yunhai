void HideCursor() {
    HANDLE hConsole = GetStdHandle(STD_OUTPUT_HANDLE); // 获取控制台句柄
    CONSOLE_CURSOR_INFO cursorInfo;
    GetConsoleCursorInfo(hConsole, &cursorInfo); // 获取当前光标信息
    cursorInfo.bVisible = FALSE;                  // 设置可见性为假
    SetConsoleCursorInfo(hConsole, &cursorInfo);  // 应用新设置
}
void setXY(int x, int y) {//获取控制台坐标 
    COORD pos;
    HANDLE obj;
    pos.X = x;
    pos.Y = y;
    obj = GetStdHandle(STD_OUTPUT_HANDLE);
    SetConsoleCursorPosition(obj, pos);
}

