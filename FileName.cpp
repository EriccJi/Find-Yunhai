int playerMove(char dir)
{
    int updateX = playerX;
    int updateY = playerY;

    // 根据方向计算新坐标
    // ground[j][i] 中 j=行(竖直方向, 0~28), i=列(水平方向, 0~30)
    // playerX 对应行号(j), playerY 对应列号(i)
    if (dir == 119) {//键入w
        updateY--;
    }
    else if (dir == 97) {//键入a
        updateX--;
    }
    else if (dir == 115) {//键入s
        updateY++;
    }
    else if (dir == 100) {//键入d
        updateX++;
    }
    if (flag >= MAX_MOVES)// 检查步数是否超过最大限制(MAX_MOVES = 2000)
    {
        return -1; // 步数用尽，游戏失败
    }

    // 检查新位置是否在地图范围内 (行:0~28, 列:0~30)
    if (updateX < 0 || updateX >= 31 || updateY < 0 || updateY >= 29)
    {
        return 0; // 超出地图边界，移动失败
    }

    // 检查新位置是否是墙(1-砖块)
    if (ground[updateY][updateX] == 1)
    {
        return 0; // 碰到砖块，移动失败
    }
    else
    {ground[playerY][playerX] = 0;// 清除玩家旧位置（恢复为空地0）
    int x = out[count - 1][1];//获取终点坐标  
    int y = out[count - 1][0];
    if (ground[x][y] == 0)
        ground[x][y] = 5;//保证终点不被玩家行动覆盖 
    // 更新玩家坐标
    playerX = updateX;
    playerY = updateY;
    // 在新位置放置玩家(值为3-玩家)
    // 步数加1
    flag++;
    return 1;// 移动成功
    }
}
int jiaoguanmove() {
    int tx, ty;                              // 教官这次要追的目标：玩家5步前站的格子
    int fx, fy;                              // 试探某个方向时用的临时坐标
    int k;                                   // 试四个方向的计数
    int dirX[4] = { 1, -1, 0, 0 };            // 四个方向：右、左、不动、不动
    int dirY[4] = { 0, 0, 1, -1 };            // 四个方向：不动、不动、下、上
    if (flag <= 4) {                         // 玩家还没走满5步
        return 0;                            // 教官原地不动
    }
    int teacherTargetX = step[0][0];                // 记下这一回合盯着的脚印，屏幕要画这个点
    int teacherTargetY = step[0][1];
    tx = step[0][0];                         // 目标列 = 队头，就是玩家5步前站的列
    ty = step[0][1];                         // 目标行 = 队头，就是玩家5步前站的行
    if (teacherX == tx && teacherY == ty) {  // 教官已经站在目标格上了
        return 0;                            // 没有要追的位置了，原地不动
    }
    if (teacherX < tx && ground[teacherY][teacherX + 1] != 1) {   // 教官在目标左边，右边那格不是墙
        teacherX = teacherX + 1;             // 教官向右走一格
        return 1;                            // 这一回合移动成功
    }
    if (teacherX > tx && ground[teacherY][teacherX - 1] != 1) {   // 教官在目标右边，左边那格不是墙
        teacherX = teacherX - 1;             // 教官向左走一格
        return 1;                            // 这一回合移动成功
    }
    if (teacherY < ty && ground[teacherY + 1][teacherX] != 1) {   // 教官在目标上面，下面那格不是墙
        teacherY = teacherY + 1;             // 教官向下走一格
        return 1;                            // 这一回合移动成功
    }
    if (teacherY > ty && ground[teacherY - 1][teacherX] != 1) {   // 教官在目标下面，上面那格不是墙
        teacherY = teacherY - 1;             // 教官向上走一格
        return 1;                            // 这一回合移动成功
    }
    for (k = 0; k < 4; k++) {                // 前后左右都被墙顶住了，四个方向挨个试
        fx = teacherX + dirX[k];             // 算出这个方向的列
        fy = teacherY + dirY[k];             // 算出这个方向的行
        if (fx >= 0 && fx <= 30 && fy >= 0 && fy <= 27 && ground[fy][fx] != 1) {  // 即没出界也不是墙
            teacherX = fx;                   // 能走，列更新
            teacherY = fy;                   // 行更新
            return 1;                        // 这一回合移动成功
        }
    }
    int x = out[count - 1][1];//获取终点坐标  
    int y = out[count - 1][0];
    if (ground[x][y] == 0)
        ground[x][y] = 5;//保证终点不被教官行动覆盖 
    return 0;                                // 当四面都是墙，教官这回合不动
}

