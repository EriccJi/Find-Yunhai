void type_print(const char* content, int speed) {
    for (int i = 0; content[i] != '\0'; i++) {
        // 一检测到按键，直接清掉所有剩余内容、直接跳出，不输出多余字符
        if (_kbhit()) {
            while (_kbhit()) _getch();
            // 直接把剩下的整段文字一次性全打出来，瞬间看完剧情
            printf("%s", content + i);
            fflush(stdout);
            return;
        }
        putchar(content[i]);
        Sleep(speed);
    }
    fflush(stdout);
}

